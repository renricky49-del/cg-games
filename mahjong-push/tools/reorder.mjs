// Re-measures every campaign level with many bot runs and re-sorts each chapter (easiest first,
// first two slots of chapters 2-5 stay as breathers). node tools/reorder.mjs
import * as L from '../js/logic.js';
import { LEVELS } from '../js/levels-data.js';
import { botWinRate } from './bot.mjs';
import { writeFileSync } from 'fs';
const levels = LEVELS.map((lv, k) => (lv.tut ? lv : { ...lv, win: +botWinRate(L.decode(lv.s), 200, 7 + k).toFixed(3) }));
for (let c = 0; c < 5; c++) {
  const start = c === 0 ? 2 : c * 12;
  const seg = levels.slice(start, (c + 1) * 12).sort((a, b) => b.win - a.win);
  levels.splice(start, seg.length, ...seg);
}
console.log(levels.map((l, i) => `${i + 1}:${Math.round(l.win * 100)}`).join(' '));
const out = `// AUTO-GENERATED by tools/build-levels.mjs (+ tools/reorder.mjs) — pinned, solver-verified campaign levels.\n` +
  `// s: board rows ('.' empty, '#' stone, letters = tile face ids), win: casual-bot win rate (no boosters, 200 runs),\n// d: composite difficulty score, dr: random-play dead-end ratio, br: avg branching\n` +
  `export const LEVELS = ${JSON.stringify(levels, null, 0).replace(/\},\{/g, '},\n{')};\n`;
writeFileSync(new URL('../js/levels-data.js', import.meta.url), out);
