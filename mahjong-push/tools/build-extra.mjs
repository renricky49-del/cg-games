// Appends chapters 6-7 (levels 61-84) to the pinned campaign without touching levels 1-60.
// Same pipeline as build-levels: seeded board -> solver proof -> casual-bot win rate -> pick nearest target
// -> re-measure with 200 runs and sort each chapter (two breathers first). node tools/build-extra.mjs
import * as L from '../js/logic.js';
import { LEVELS } from '../js/levels-data.js';
import { botWinRate } from './bot.mjs';
import { writeFileSync } from 'fs';
if (LEVELS.length !== 60) { console.log('already extended:', LEVELS.length); process.exit(0); }
const faces = [...Array(38).keys()];
const out = LEVELS.slice();
for (let c = 5; c <= 6; c++) {
  const chapter = [];
  for (let i = 0; i < 12; i++) {
    const level = c * 12 + i + 1, p = i / 11;
    const [w, h] = i < 2 ? [9, 8] : [10, 8];
    const stones = (c === 5 ? 3 : 4) + Math.round(p * 1.5);
    const pairs = Math.round((w * h - stones) * (0.56 + 0.06 * p) / 2);
    const types = Math.min(38, Math.round(pairs * (c === 5 ? 0.5 : 0.56)));
    const target = (c === 5 ? 0.55 : 0.48) - (c === 5 ? 0.25 : 0.26) * p;
    const cands = [];
    for (let s = 0; cands.length < 12 && s < 90; s++) {
      const seed = level * 100003 + s * 7919, rnd = L.mulberry32(seed ^ 0x5bd1e995);
      const pool = L.shuffleArr(faces.slice(), rnd).slice(0, types);
      const b = L.generateBoard({ w, h, pairs, types, stones, typePool: pool }, seed);
      if (!L.hasMove(b.cells, w, h) || !L.solve(b.cells, w, h, 40000).solution) continue;
      cands.push({ b, win: botWinRate(b, 100, seed + 1), seed });
    }
    cands.sort((a, b) => Math.abs(a.win - target) - Math.abs(b.win - target));
    const pick = cands[0];
    const m = L.analyze(pick.b.cells, w, h, 40, pick.seed);
    const win = botWinRate(pick.b, 200, level + 7);
    chapter.push({ s: L.encode(pick.b), d: +(m.deadRatio + 0.25 * (pairs * 2 / 70)).toFixed(3), win: +win.toFixed(3), dr: m.deadRatio, br: +m.branch.toFixed(1) });
    console.log(level, `${w}x${h}`, 'pairs', pairs, 'types', types, 'stones', stones, 'target', target.toFixed(2), 'win', win.toFixed(2));
  }
  const head = chapter.slice(0, 2).sort((a, b) => b.win - a.win), rest = chapter.slice(2).sort((a, b) => b.win - a.win);
  out.push(...head, ...rest);
}
const txt = `// AUTO-GENERATED by tools/build-levels.mjs (+ tools/reorder.mjs, tools/build-extra.mjs) — pinned, solver-verified campaign levels.\n` +
  `// s: board rows ('.' empty, '#' stone, letters = tile face ids), win: casual-bot win rate (no boosters, 200 runs),\n// d: composite difficulty score, dr: random-play dead-end ratio, br: avg branching\n` +
  `export const LEVELS = ${JSON.stringify(out, null, 0).replace(/\},\{/g, '},\n{')};\n`;
writeFileSync(new URL('../js/levels-data.js', import.meta.url), txt);
console.log('levels now', out.length);
