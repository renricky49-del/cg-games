// Generates the pinned campaign: node tools/build-levels.mjs  -> js/levels-data.js
// Each level = seeded random board, verified solvable by the DFS solver, scored by random-playout
// dead-end ratio + branching factor, then the candidate nearest the target difficulty is picked.
import * as L from '../js/logic.js';
import { writeFileSync } from 'fs';
import { botWinRate } from './bot.mjs';

// Face ids (see tiles.js): 0-8 dots, 9-17 bamboo, 18-20 dragons, 21-24 winds, 25-33 characters, 34-37 flowers
const range = (a, b) => [...Array(b - a + 1).keys()].map((i) => i + a);
const CHAPTER_FACES = [
  range(0, 17).concat(range(18, 20)),
  range(0, 24),
  range(0, 24).concat(range(34, 37)),
  range(0, 37),
  range(0, 37),
];

// Tutorial levels (hand made). Letters map to face ids via the per-level faces array.
const TUTORIAL = [
  { str: 'a.a./b..b/cc..', faces: [0, 1, 2], tut: 'match' },
  { str: 'a.../.b../..../.ab.', faces: [9, 4], tut: 'push' },
];

// Per-level generation params, chapter c (0-4), index within chapter i (0-11)
function params(level) {
  // level: 1-based campaign index
  const c = Math.floor((level - 1) / 12);
  const i = (level - 1) % 12;
  const p = (level - 3) / 57; // 0..1 overall progress
  const sizes = [
    [[4, 5], [4, 5], [5, 5], [5, 6], [5, 6], [5, 6], [6, 6], [6, 6], [6, 6], [6, 7]],
    [[5, 6], [6, 6], [6, 6], [6, 7], [6, 7], [6, 7], [6, 7], [7, 7], [7, 7], [7, 7], [7, 7], [7, 8]],
    [[6, 7], [7, 7], [7, 7], [7, 8], [7, 8], [7, 8], [7, 8], [7, 8], [8, 8], [8, 8], [8, 8], [8, 9]],
    [[7, 8], [7, 8], [8, 8], [8, 8], [8, 9], [8, 9], [8, 9], [8, 9], [8, 9], [8, 10], [8, 10], [8, 10]],
    [[8, 8], [8, 9], [8, 9], [8, 9], [8, 10], [8, 10], [8, 10], [8, 10], [8, 10], [8, 10], [8, 10], [8, 10]],
  ];
  const [h, w] = c === 0 ? sizes[0][i - 2] : sizes[c][i]; // rows x cols, landscape-ish
  const cells = w * h;
  const density = 0.5 + 0.18 * p + (c === 0 ? -0.05 : 0); // fraction of cells filled with tiles
  const stones = c === 0 ? 0 : Math.round((1 + c) * (0.4 + 0.6 * (i / 11)));
  let pairs = Math.max(4, Math.round((cells - stones) * density / 2));
  const types = Math.max(3, Math.min(CHAPTER_FACES[c].length, Math.round(pairs * (0.45 + 0.2 * p))));
  // target random-playout dead ratio: smooth ramp with a small breather at chapter start
  const breather = i === 0 ? 0.12 : i === 1 ? 0.06 : 0;
  // target win rate of the casual bot (no boosters): 100% -> ~25% at the end, breathers at chapter starts
  const target = Math.min(1, 1.0 - 0.75 * Math.pow(p, 0.85) + breather);
  return { c, i, w, h, pairs, types, stones, target };
}

function score(m, tiles) {
  // composite difficulty (0..~1.5): dead ratio dominates, fewer options and more tiles add a bit
  return m.deadRatio + 0.25 * (tiles / 70) + 0.15 * Math.max(0, 1 - m.branch / 25);
}

const levels = [];
TUTORIAL.forEach((t, k) => {
  const b = L.decode(t.str);
  const cells = b.cells.map((v) => (v >= 0 ? t.faces[v] : v));
  levels.push({ s: L.encode({ ...b, cells }), tut: t.tut, d: 0, win: 1 });
});

const t0 = Date.now();
for (let level = 3; level <= 60; level++) {
  const P = params(level);
  const cands = [];
  for (let s = 0; cands.length < 14 && s < 100; s++) {
    const seed = level * 100003 + s * 7919;
    const rnd = L.mulberry32(seed ^ 0x5bd1e995);
    const pool = L.shuffleArr(CHAPTER_FACES[P.c].slice(), rnd).slice(0, P.types);
    const b = L.generateBoard({ w: P.w, h: P.h, pairs: P.pairs, types: P.types, stones: P.stones, typePool: pool }, seed);
    if (!L.hasMove(b.cells, b.w, b.h)) continue;
    const sol = L.solve(b.cells, b.w, b.h, 40000);
    if (!sol.solution) continue;
    const m = L.analyze(b.cells, b.w, b.h, 40, seed);
    m.win = botWinRate(b, 40, seed + 1);
    cands.push({ b, m, seed, sc: score(m, P.pairs * 2) });
  }
  cands.sort((a, b) => Math.abs(a.m.win - P.target) - Math.abs(b.m.win - P.target));
  const pick = cands[0];
  levels.push({ s: L.encode(pick.b), d: +pick.sc.toFixed(3), win: pick.m.win, dr: pick.m.deadRatio, br: +pick.m.branch.toFixed(1), i: P.i });
  console.log(level, `${P.w}x${P.h}`, 'pairs', P.pairs, 'types', P.types, 'stones', P.stones,
    'target', P.target.toFixed(2), 'got', pick.m.win.toFixed(2), 'dead', pick.m.deadRatio.toFixed(2), 'cands', cands.length);
}
// Order levels within each chapter by composite score (tutorials stay first).
for (let c = 0; c < 5; c++) {
  const start = c === 0 ? 2 : c * 12;
  // keep the chapter-start breathers in front, sort the rest by bot win rate (easiest first)
  const seg = levels.slice(start, (c + 1) * 12);
  const head = c === 0 ? [] : seg.slice(0, 2).sort((a, b) => b.win - a.win);
  const rest = (c === 0 ? seg : seg.slice(2)).sort((a, b) => b.win - a.win || a.d - b.d);
  levels.splice(start, seg.length, ...head, ...rest);
}
console.log('built in', Date.now() - t0, 'ms');
const out = `// AUTO-GENERATED by tools/build-levels.mjs — pinned, solver-verified campaign levels.\n` +
  `// s: board rows ('.' empty, '#' stone, letters = tile face ids), win: casual-bot win rate (no boosters),\n// d: composite difficulty score, dr: random-play dead-end ratio, br: avg branching, i: slot in chapter\n` +
  `export const LEVELS = ${JSON.stringify(levels, null, 0).replace(/\},\{/g, '},\n{')};\n`;
writeFileSync(new URL('../js/levels-data.js', import.meta.url), out);
