// Adds red-cord tied tiles to campaign levels 27-84 (pinned data, solver-verified).
// For each level: try candidate tie sets, keep only solver-proven solvable ones, and pick the set whose
// casual-bot win rate is closest to (original - 0.04): ties add a new idea without a difficulty spike.
// node tools/add-ties.mjs   (idempotent: skips levels that already contain ties)
import * as L from '../js/logic.js';
import { LEVELS } from '../js/levels-data.js';
import { botWinRate } from './bot.mjs';
import { writeFileSync } from 'fs';
const tiesFor = (n) => (n < 27 ? 0 : n <= 36 ? 1 + (n >= 31 ? 1 : 0) : n <= 48 ? 2 : n <= 60 ? (n >= 55 ? 3 : 2) : n <= 72 ? 3 : (n >= 79 ? 4 : 3));
const out = LEVELS.map((lv) => ({ ...lv }));
for (let n = 27; n <= out.length; n++) {
  const lv = out[n - 1];
  if (lv.s.includes('!')) continue;
  const k = tiesFor(n);
  const base = L.decode(lv.s);
  const target = Math.max(0.05, (lv.win ?? 0.5) - 0.04);
  let best = null;
  for (let t = 0; t < 14; t++) {
    const cells = L.tieTiles(base.cells.slice(), k, L.mulberry32(n * 7919 + t));
    if (!L.hasMove(cells, base.w, base.h) || !L.solve(cells, base.w, base.h, 40000).solution) continue;
    const win = botWinRate({ ...base, cells }, 60, n + t);
    if (!best || Math.abs(win - target) < Math.abs(best.win - target)) best = { cells, win };
    if (Math.abs(win - target) < 0.03) break;
  }
  if (!best) { console.log(n, 'no solvable tie set, left untied'); continue; }
  out[n - 1] = { ...lv, s: L.encode({ ...base, cells: best.cells }), win: +best.win.toFixed(3), ties: k };
  console.log(n, 'ties', k, 'win', (lv.win ?? 0).toFixed(2), '->', best.win.toFixed(2));
}
const txt = `// AUTO-GENERATED by tools/build-levels.mjs (+ reorder.mjs, build-extra.mjs, add-ties.mjs) — pinned, solver-verified campaign levels.\n` +
  `// s: board rows ('.' empty, '#' stone, letters = tile face ids, '!' before a letter = tied tile), win: casual-bot win rate (no boosters),\n// d: composite difficulty score, dr: random-play dead-end ratio, br: avg branching, ties: tied tiles\n` +
  `export const LEVELS = ${JSON.stringify(out, null, 0).replace(/\},\{/g, '},\n{')};\n`;
writeFileSync(new URL('../js/levels-data.js', import.meta.url), txt);
console.log('done');
